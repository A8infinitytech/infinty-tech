export type FieldType =
  | "text"
  | "textarea"
  | "email"
  | "url"
  | "number"
  | "boolean"
  | "image"
  | "select";

export type FieldConfig = {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  options?: readonly string[];
  help?: string;
};

export type EntityConfig = {
  key: string;
  table: string;
  label: string;
  group: string;
  kind: "singleton" | "list";
  fields: readonly FieldConfig[];
  orderBy: string;
  searchable?: boolean;
};

const field = (
  name: string,
  label: string,
  type: FieldType = "text",
  extra: Partial<FieldConfig> = {},
): FieldConfig => ({ name, label, type, ...extra });

